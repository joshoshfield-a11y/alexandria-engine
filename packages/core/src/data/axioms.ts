export type AxiomPillarId = 'foundational' | 'cosmic' | 'choral' | 'transcendent';

export type AxiomVerdict = 'ANCHOR' | 'DEFINE-proposed' | 'SYMBOLIC-ONLY';

export interface Axiom {
  /** 1–78, source order for 1–72, canon order for 73–78 */
  id: number;
  glyph: string;
  /** Plain-language name — the primary identity. */
  name: string;
  /** Original Codex name, preserved for provenance. */
  codexName: string;
  meaning: string;
  pillar: AxiomPillarId;
  /** The question this axiom asks when applied as an operator. */
  asks: string;
  /** Grounding-pass verdict for this operator (canon-78.csv). */
  verdict: AxiomVerdict;
  /** What the operator anchors to — standard-form provenance (work/*.md). */
  groundedSource: string;
}

